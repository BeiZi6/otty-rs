"""Generate `packages/config/src/keys.rs` from `spec/config-schema.json`.

The registry is data; `spec.rs` holds the types and the lookups.
Usage: python tools/gen_keys.py
"""
import json
import pathlib
import sys

SCHEMA = pathlib.Path(r"E:\study_serve\otty-re\otty\spec\config-schema.json")
OUT = pathlib.Path(r"E:\study_serve\otty-re\otty\packages\config\src\keys.rs")
KNOWN_KEYS = pathlib.Path(r"E:\study_serve\otty-re\analysis\config_keys.txt")

KIND = {
    "string": "KeyKind::Str",
    "bool": "KeyKind::Bool",
    "int": "KeyKind::Int",
    "float": "KeyKind::Float",
    "color": "KeyKind::Color",
    "enum": "KeyKind::Enum",
    "list": "KeyKind::Repeated",       # refined below by list_style
    "key-value": "KeyKind::Pairs",
    "rule": "KeyKind::Rule",
}


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").replace("\r", "") + '"'


def default_expr(spec: dict) -> tuple[str, str]:
    d = spec.get("default")
    note = spec.get("default_note") or ""
    if d is None:
        return "Default::Derived", rust_str(note if note else "not documented")
    if isinstance(d, bool):
        return f"Default::Bool({str(d).lower()})", rust_str(note)
    if isinstance(d, int):
        return f"Default::Int({d})", rust_str(note)
    if isinstance(d, float):
        return f"Default::Float({d!r})", rust_str(note)
    if isinstance(d, list):
        items = ", ".join(rust_str(str(x)) for x in d)
        return f"Default::List(&[{items}])", rust_str(note)
    text = str(d)
    if spec.get("kind") == "color":
        return f"Default::Color({rust_str(text)})", rust_str(note)
    return f"Default::Str({rust_str(text)})", rust_str(note)


def kind_expr(spec: dict) -> str:
    k = spec.get("kind", "string")
    if k == "list":
        style = (spec.get("list_style") or "repeated").lower()
        return "KeyKind::Repeated" if style == "repeated" else "KeyKind::List"
    return KIND.get(k, "KeyKind::Str")


def main() -> None:
    data = json.loads(SCHEMA.read_text(encoding="utf-8"))
    specs = data["keys"]

    # Aliases are *one-directional*: a legacy spelling points at the key the
    # Configuration Reference documents. The schema carries some pairs in both
    # directions (the shipped registry knows `shell` as a key, and the reference
    # calls it an alias of `command`), so the directions are normalised here.
    LEGACY = {
        "shell": "command",
        "font-smooth": "font-blending",
        "font-antialiased": "font-blending",
        "ligatures": "font-ligatures",
        "font-bold": "text-bold",
        "font-italic": "text-italic",
        "font-underline": "text-underline",
        "font-blink": "text-blink",
        "window-show-tab-bar": "auto-hide-tab-bar",
        "open-quickly-zoxide-limit": "open-quickly-folders-limit",
    }
    dropped = [s["key"] for s in specs if s["key"] in LEGACY]
    specs = [s for s in specs if s["key"] not in LEGACY]
    known_names = {s["key"] for s in specs}
    for s in specs:
        # Keep the canonical spelling of every legacy name that points here, and
        # any alias that is not itself a registered key; drop reverse pointers.
        merged = set(s.get("aliases") or [])
        merged |= {k for k, v in LEGACY.items() if v == s["key"]}
        merged = {a for a in merged if a not in known_names}
        s["aliases"] = sorted(merged)
    if dropped:
        print(f"folded {len(dropped)} legacy spellings into their canonical key: {dropped}")

    UNDOCUMENTED = "not documented in the Configuration Reference"
    shadowed = set(LEGACY)
    declared = sorted({l.strip() for l in KNOWN_KEYS.read_text(encoding="utf-8").splitlines() if l.strip()})
    # `config_keys.txt` comes from the shipped build's generated editor-syntax
    # file, which covers the 16 per-index palette keys with its generic
    # `key =` pattern instead of listing them. The Configuration Reference does
    # list them, so the registry has 16 more entries than that file.
    declared += [f"palette-{i}" for i in range(16)]
    declared = [k for k in declared if k not in shadowed]

    have = {s["key"] for s in specs}
    missing = [k for k in declared if k not in have]
    extra = [k for k in have if k not in declared]
    if missing or extra:
        print(f"FATAL: registry mismatch\n  missing ({len(missing)}): {missing}\n  extra ({len(extra)}): {extra}")
        sys.exit(1)

    lines = [
        "//! The config key registry — pure data.",
        "//!",
        "//! Generated by `tools/gen_keys.py` from `spec/config-schema.json`, which is",
        "//! itself derived from the shipped build's Configuration Reference plus the",
        "//! `Config::known_keys()` list the app encodes in its generated editor-syntax",
        "//! files. Do not edit by hand.",
        "//!",
        "//! The types and the lookups live in [`crate::spec`].",
        "",
        "use crate::spec::{Default, KeySpec, ListStyle};",
        "use crate::value::KeyKind;",
        "",
        f"/// Every key Otty recognises ({len(specs)}).",
        "pub static KEYS: &[KeySpec] = &[",
    ]
    for s in specs:
        default, note = default_expr(s)
        enums = s.get("enum_values") or []
        if enums:
            ev = "&[" + ", ".join(rust_str(str(v)) for v in enums) + "]"
        else:
            ev = "&[]"
        aliases = s.get("aliases") or []
        al = "&[" + ", ".join(rust_str(a) for a in aliases) + "]" if aliases else "&[]"
        style = s.get("list_style")
        if s.get("kind") == "list" and style and style.lower() == "inline":
            ls = "Some(ListStyle::Inline)"
        elif s.get("kind") == "list" or s.get("kind") in ("key-value", "rule"):
            ls = "Some(ListStyle::Repeated)"
        else:
            ls = "None"
        lines.append("    KeySpec {")
        lines.append(f"        key: {rust_str(s['key'])},")
        lines.append(f"        section: {rust_str(s.get('section') or 'General')},")
        lines.append(f"        kind: {kind_expr(s)},")
        lines.append(f"        default: {default},")
        lines.append(f"        default_note: {note},")
        lines.append(f"        enum_type: {rust_str(s.get('enum_type') or '')},")
        lines.append(f"        enum_values: {ev},")
        lines.append(f"        aliases: {al},")
        lines.append(f"        platform: {rust_str(s.get('platform') or 'all')},")
        lines.append(f"        list_style: {ls},")
        lines.append(f"        value_shape: {rust_str(s.get('value_shape') or '')},")
        lines.append(f"        doc: {rust_str(s.get('description') or '')},")
        lines.append("    },")
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(specs)} keys -> {OUT}")


if __name__ == "__main__":
    main()
