"""Emit `packages/config/src/actions.rs` — the keybinding action registry.

The action ids and their labels are read verbatim from the shipped app's
localization catalog (`en.json` -> `settings.key_bindings.actions`), which is
what the Settings -> Key Bindings panel lists.

Usage: python tools/gen_actions.py
"""
import json
import pathlib

EN = pathlib.Path(r"E:\study_serve\otty-re\dmg\arm64\Otty\Otty.app\Contents\Resources\en.json")
OUT = pathlib.Path(r"E:\study_serve\otty-re\otty\packages\config\src\actions.rs")

data = json.loads(EN.read_text(encoding="utf-8"))
actions = data["settings"]["key_bindings"]["actions"]

# Group membership, inferred from the action-id namespace. The Settings panel
# exposes these groups to the user; the ids themselves come from the app.
GROUPS = [
    ("general", [
        "command_palette", "open_quickly", "jump_to", "jump_to_selection", "open_settings",
        "open_config_file", "reload_config", "open_recent", "open_folder", "open_files_quickly",
        "open_agent", "workspace_commands", "switch_open_tab", "quit", "merge_all_windows",
        "pin_window", "theme_palette", "view_as_jsonl", "view_as_agent_history",
        "syntax_auto_detect", "new_editor", "new_folder_pane", "split_view", "resize",
        "open_with_default_app", "reveal_in_finder", "copy_path", "insert_file_path",
        "insert_screenshot", "export_selected_text", "export_text", "picture_in_picture",
        "picture_in_picture_follow", "close_picture_in_picture", "show_scrollback_history",
        "toggle_remote_access", "toggle_secure_input", "reset_terminal",
        "clear_scrollback_above", "send_to_chat",
    ]),
    ("window", ["new_window", "close_window", "minimize", "toggle_full_screen"]),
    ("tabs", [
        "new_tab", "close_tab", "reopen_closed_tab", "next_tab", "previous_tab", "duplicate_tab",
        "rename_tab", "prefix_tab", "move_tab_to_new_window", "show_unread_tab",
        "toggle_tabs_panel", "tabs_insert_divider", "tabs_remove_dividers",
    ]),
    ("pane", [
        "split_right", "split_left", "split_down", "split_up", "zoom_split", "equalize_splits",
        "focus_next_pane", "focus_previous_pane", "focus_pane_up", "focus_pane_down",
        "focus_pane_left", "focus_pane_right", "move_divider_up", "move_divider_down",
        "move_divider_left", "move_divider_right", "switch_pane_to_folder",
        "switch_pane_to_terminal", "toggle_details_panel",
    ]),
    ("agents", [
        "agent_branch", "agent_fork", "agent_fork_new_tab", "agent_fork_new_window",
        "agent_fork_split_down", "agent_fork_split_left", "agent_fork_split_right",
        "agent_fork_split_up", "open_agent",
    ]),
    ("edit", [
        "copy", "cut", "paste", "paste_bracketed", "paste_selection", "paste_shell_escaped",
        "paste_file_base64", "paste_continue_composer", "select_all", "undo", "redo",
    ]),
    ("text_editing", [
        "cursor_line_start", "cursor_line_end", "cursor_word_left", "cursor_word_right",
        "delete_word_left", "delete_word_right", "delete_to_line_start", "delete_to_line_end",
    ]),
    ("scroll", [
        "scroll_up", "scroll_down", "scroll_page_up", "scroll_page_down", "scroll_to_top",
        "scroll_to_bottom",
    ]),
    ("view", [
        "increase_font_size", "decrease_font_size", "reset_font_size", "clear_screen",
        "find", "find_next", "find_previous", "global_search", "use_selection_for_find",
        "search_in_files", "toggle_vi_mode", "toggle_vi_mode_help", "toggle_mark_mode",
        "toggle_hint_mode", "hint_copy", "hint_open", "hint_paste", "hint_reveal",
        "toggle_read_only", "compose_overlay", "prompt_queue_add", "prompt_queue_clear",
    ]),
    ("recipe", ["save_recipe", "save_recipe_as"]),
]

group_of = {}
for g, ids in GROUPS:
    for i in ids:
        assert i in actions, f"unknown action id in group {g}: {i}"
        group_of[i] = g

unknown = [a for a in actions if a not in group_of]
for a in unknown:  # numeric tab jumps and any leftover
    if a.startswith("goto_tab_") or a.startswith("details_tab_") or a.startswith("tabs_group_") \
            or a.startswith("tabs_order_"):
        continue
    print(f"note: grouping `{a}` under `general` (no explicit group)")

body = [
    "//! The keybinding action registry.",
    "//!",
    "//! Generated by `tools/gen_actions.py` from the shipped app's localization",
    "//! catalog (`en.json` -> `settings.key_bindings.actions`), which is exactly",
    "//! what Settings -> Key Bindings lists. Do not edit by hand.",
    "//!",
    "//! Each entry is `(id, label)`. The id is the value that appears on the",
    "//! right-hand side of a `keybind = trigger=action` line in `config.toml`.",
    "",
    "/// Every assignable action, `(id, human label)`, sorted by id.",
    "pub static ACTIONS: &[(&str, &str)] = &[",
]
for k in sorted(actions):
    label = actions[k].replace("\\", "\\\\").replace('"', '\\"')
    body.append(f'    ("{k}", "{label}"),')
body.append("];")
body.append("")
body.append(f"/// How many actions ship unbound or bound by default: {len(actions)}.")
body.append("pub const ACTION_COUNT: usize = ACTIONS.len();")
body.append("")

OUT.write_text("\n".join(body), encoding="utf-8")
print(f"{len(actions)} actions -> {OUT}")
